"""
Генератор типизированных моделей PgOrm (JasMaman.FcMigrator/Models) из schema.json.

Повторяет формат моделей keleshek.GonsMigrator:
  - [PgTable("ctNNN")] + IPgEntityModel, свойства Id и Raw;
  - [PgColumn("логическое_имя")] на каждой колонке;
  - ссылка на таблицу из генерируемого набора -> свойство типа этой модели,
    ссылка вне набора -> PgEntityRef?; в обоих случаях companion "{Имя}Id" (long?);
  - многоязычные колонки (column_overrides.json: cmNNNN -> cmNNNN_1, cmNNNN_2)
    дополнительно получают свойство "{Имя}_kz" ([PgColumn("имя_2")]).

Запуск из корня решения:
    python tools/generate_models.py

Набор таблиц - TABLES ниже. После изменения набора перезапустить генератор:
типы ссылок между моделями зависят от того, какие таблицы входят в набор.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "JasMaman.FcMigrator" / "Schema" / "schema.json"
COLUMN_OVERRIDES = ROOT / "JasMaman.FcMigrator" / "Overrides" / "column_overrides.json"
OUT_DIR = ROOT / "JasMaman.FcMigrator" / "Models"

# Таблицы УМОСК, для которых нужны модели (см. docs/fin_center-umosk.md).
TABLES = [
    # Основные
    "ct320",  # Персона
    "ct321",  # Зап_перс_данных (ФИО, ИИН)
    "ct322",  # Зап_обучения
    "ct520",  # Зап_отработки_МС
    "ct581",  # Зап_статуса_ТКС (история ТКС)
    "ct663",  # Зап_табл_предварительных_статусов (статус мониторинга)
    # Справочники
    "ct317",  # ВУЗ
    "ct316",  # Специальность
    "ct325",  # Область
    "ct450",  # Классификатор_КАТО
    "ct314",  # Движение
    "ct360",  # Статус_заемщика_ткс
    "ct464",  # Статус_УМС (категория гранта)
    "ct539",  # Статус мониторинга
    "ct664",  # Предварительный статус УМС
    "ct583",  # Разделение мест распределения_МС
    "ct436",  # Освобождение_от_отработки
    "ct438",  # Прекращение_обязан_по_отработке
    "ct452",  # Льгота_при_распределении
    "ct454",  # Форма обучения
    "ct524",  # Язык_обучения
    "ct574",  # Основание отчисления из ВУЗа
    "ct535",  # Статус_физлица
    "ct596",  # Статус_учета ЦЗН
    "ct572",  # Тип_документа УМС
    "ct582",  # Тип_подтверджающего документа УМС
]

PRIMITIVES = {
    "string": "string?",
    "memo": "string?",
    "long": "long?",
    "float": "double?",
    "date": "DateTime?",
    "boolean": "bool?",
}


def class_name(logical: str) -> str:
    short = logical.split("::")[-1]
    parts = [p for p in re.split(r"[^0-9A-Za-zА-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІі]+", short) if p]
    name = "".join(p[0].upper() + p[1:] for p in parts)
    return name if not name[0].isdigit() else "_" + name


def prop_name(logical: str) -> str:
    name = re.sub(r"[^0-9A-Za-zА-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІі]+", "_", logical).strip("_")
    if not name:
        name = "Col"
    name = name[0].upper() + name[1:]
    return name if not name[0].isdigit() else "_" + name


def main() -> int:
    tables = json.loads(SCHEMA.read_text(encoding="utf-8"))["tables"]
    multilang = {}
    if COLUMN_OVERRIDES.exists():
        multilang = json.loads(COLUMN_OVERRIDES.read_text(encoding="utf-8"))
    else:
        print(f"нет {COLUMN_OVERRIDES} - многоязычные колонки не будут размечены "
              f"(запустите FcProbe dump, чтобы сгенерировать оверрайды)", file=sys.stderr)

    names = {}
    for tid in TABLES:
        name = class_name(tables[tid]["name"])
        if name in names.values():
            name = f"{name}_{tid}"
        names[tid] = name

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for old in OUT_DIR.glob("*.cs"):
        old.unlink()

    for tid in TABLES:
        write_model(tid, tables[tid], names, multilang.get(tid, {}))
    print(f"Сгенерировано моделей: {len(TABLES)} -> {OUT_DIR}")
    return 0


def write_model(tid: str, table: dict, names: dict, table_multilang: dict) -> None:
    cls = names[tid]
    used = {"Id", "Raw", cls}
    lines = [
        "// <auto-generated/>",
        "// Сгенерировано tools/generate_models.py из schema.json.",
        f"// Источник: {tid} ({table['name']})",
        "#nullable enable",
        "using System;",
        "",
        "namespace PgOrm.Models;",
        "",
        f'[PgTable("{tid}")]',
        f"public sealed class {cls} : IPgEntityModel",
        "{",
        "    /// <summary>Первичный ключ строки (c_obj_id).</summary>",
        "    public long Id { get; set; }",
        "",
        "    /// <summary>Исходная строка из ORM (доступ к колонкам, которых нет в этой модели).</summary>",
        "    public PgEntity? Raw { get; set; }",
    ]

    def unique(name: str) -> str:
        candidate, i = name, 2
        while candidate in used:
            candidate, i = f"{name}{i}", i + 1
        used.add(candidate)
        return candidate

    for col in table["columns"]:
        logical, ctype, physical = col["name"], col["type"], col["physical"]
        prop = unique(prop_name(logical))
        if ctype == "ref":
            ref_name = col.get("refTableName", col.get("refTable"))
            ref_type = names.get(col.get("refTable"), "PgEntityRef")
            lines += [
                "",
                f"    /// <summary>{logical} ({physical}, ref, -> {ref_name})</summary>",
                f'    [PgColumn("{logical}")]',
                f"    public {ref_type}? {prop} {{ get; set; }}",
                "",
                f'    /// <summary>id связанной строки "{logical}" ({ref_name}) - доступен независимо от глубины подгрузки связей.</summary>',
                f'    [PgColumn("{logical}")]',
                f"    public long? {unique(prop + 'Id')} {{ get; set; }}",
            ]
            continue

        cs_type = PRIMITIVES.get(ctype, "object?")
        lines += [
            "",
            f"    /// <summary>{logical} ({physical}, {ctype})</summary>",
            f'    [PgColumn("{logical}")]',
            f"    public {cs_type} {prop} {{ get; set; }}",
        ]
        if physical in table_multilang and cs_type == "string?":
            lines += [
                "",
                f"    /// <summary>{logical} на казахском ({physical}_2)</summary>",
                f'    [PgColumn("{logical}_2")]',
                f"    public string? {unique(prop + '_kz')} {{ get; set; }}",
            ]

    lines += ["}", ""]
    (OUT_DIR / f"{cls}.cs").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main())
